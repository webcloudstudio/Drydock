func TestOperations(t *testing.T) {
	ctx := context.Background()
	dsn := os.Getenv("DRYDOCK_TEST_POSTGRES_DSN")
	if dsn == "" {
		dsn = filepath.Join(t.TempDir(), "store.db")
	}
	schema := Schema{Tables: []Table{{Name: "library_items", Columns: []string{"id", "title"}, Key: "id"}}, Operations: []Operation{
		{ID: "create", Table: "library_items", Verb: "create", Inputs: []string{"title"}},
		{ID: "get", Table: "library_items", Verb: "get", Inputs: []string{"id"}},
		{ID: "list", Table: "library_items", Verb: "list", Inputs: []string{"title"}},
		{ID: "update", Table: "library_items", Verb: "update", Inputs: []string{"id", "title"}},
		{ID: "delete", Table: "library_items", Verb: "delete", Inputs: []string{"id"}},
	}}
	db, err := Open(ctx, dsn, schema)
	if err != nil {
		t.Fatal(err)
	}
	defer db.Close()
	ddl := `CREATE TABLE IF NOT EXISTS "library_items" ("id" INTEGER PRIMARY KEY, "title" VARCHAR(20) NOT NULL);`
	if err = db.ApplySchema(ctx, ddl); err != nil {
		t.Fatal(err)
	}
	if err = db.ApplySchema(ctx, ddl); err != nil {
		t.Fatal(err)
	}
	created, err := db.Run(ctx, "library_items", "create", map[string]any{"title": "quote ' value"})
	if err != nil {
		t.Fatal(err)
	}
	defer db.Run(ctx, "library_items", "delete", map[string]any{"id": created.ID})
	row, err := db.Run(ctx, "library_items", "get", map[string]any{"id": created.ID})
	if err != nil || len(row.Rows) != 1 || row.Rows[0]["title"] != "quote ' value" {
		t.Fatalf("get: %v %v", row, err)
	}
	updated, err := db.Run(ctx, "library_items", "update", map[string]any{"id": created.ID, "title": "updated"})
	if err != nil || updated.Count != 1 {
		t.Fatalf("update: %v %v", updated, err)
	}
	rows, err := db.Run(ctx, "library_items", "list", map[string]any{"title": "updated"})
	if err != nil || len(rows.Rows) != 1 {
		t.Fatalf("list: %v %v", rows, err)
	}
	if _, err = db.Run(ctx, "library_items", "create", map[string]any{"other": "value"}); err == nil {
		t.Fatal("accepted unknown input")
	}
	if _, err = db.Run(ctx, "library_items", "drop", nil); !errors.Is(err, ErrUnknownOperation) {
		t.Fatal("missing unknown-operation error", err)
	}
	if _, err = db.Run(ctx, "library_items", "create", map[string]any{"title": nil}); err == nil {
		t.Fatal("ignored NOT NULL")
	}
	if db.engine == "postgres" {
		if _, err = db.Run(ctx, "library_items", "create", map[string]any{"title": "a value longer than twenty characters"}); err == nil {
			t.Fatal("ignored length")
		}
	}
	deleted, err := db.Run(ctx, "library_items", "delete", map[string]any{"id": created.ID})
	if err != nil || deleted.Count != 1 {
		t.Fatalf("delete: %v %v", deleted, err)
	}
	row, err = db.Run(ctx, "library_items", "get", map[string]any{"id": created.ID})
	if err != nil || len(row.Rows) != 0 {
		t.Fatalf("missing get: %v %v", row, err)
	}
}

func TestDriverScalarConversion(t *testing.T) {
	type Row struct {
		Amount  float64 `json:"amount"`
		Enabled bool    `json:"enabled"`
		Label   string  `json:"label"`
	}
	rows, err := Decode[[]Row]([]map[string]any{{"amount": "12.5", "enabled": int64(1), "label": "123"}})
	if err != nil || len(rows) != 1 || rows[0].Amount != 12.5 || !rows[0].Enabled || rows[0].Label != "123" {
		t.Fatalf("%v %v", rows, err)
	}
	if _, err = Decode[Row](map[string]any{"amount": "not numeric"}); err == nil {
		t.Fatal("invalid numeric conversion accepted")
	}
}

func TestIdentityDDLDoesNotChangeLiteralValues(t *testing.T) {
	ddl := `CREATE TABLE "example" ("id" INTEGER PRIMARY KEY, "note" TEXT DEFAULT '"id" INTEGER PRIMARY KEY');`
	want := `CREATE TABLE "example" ("id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "note" TEXT DEFAULT '"id" INTEGER PRIMARY KEY');`
	if got := postgresSchema(ddl); got != want {
		t.Fatalf("%s", got)
	}
}
