package persistence

import (
	"database/sql"
	"regexp"
	"strings"

	_ "github.com/lib/pq"
)

func openPostgres(dsn string) (*sql.DB, error) { return sql.Open("postgres", dsn) }

// SQLite INTEGER PRIMARY KEY allocates an identity; PostgreSQL needs it declared explicitly.
var identityColumn = regexp.MustCompile(`(?m)("[a-z][a-z0-9_]*"\s+)INTEGER PRIMARY KEY`)

func postgresSchema(ddl string) string {
	parts := strings.Split(ddl, "'")
	for i := 0; i < len(parts); i += 2 {
		parts[i] = identityColumn.ReplaceAllString(parts[i], `${1}INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY`)
	}
	return strings.Join(parts, "'")
}
